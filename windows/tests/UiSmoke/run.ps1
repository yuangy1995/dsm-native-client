    @('nas-power-settings', 'Light', 'power-rejected'), @('nas-power-settings', 'Light', 'power-pending'),
    @('nas-power-settings', 'Light', 'power-fresh'), @('nas-power-settings', 'Light', 'power-switch-action'),
    @('nas-power-settings', 'Light', 'power-close-busy'),
    @('nas-connection-settings', 'Light', 'conn-readonly'), @('nas-connection-settings', 'Dark', 'conn-readonly'),
    @('nas-connection-settings', 'Light', 'conn-empty'), @('nas-connection-settings', 'Light', 'conn-loading'),
    @('nas-connection-settings', 'Light', 'conn-error'), @('nas-connection-settings', 'Light', 'conn-partial'),
    @('nas-connection-settings', 'Light', 'conn-missing'), @('nas-connection-settings', 'Light', 'conn-ambiguous'),
    @('nas-connection-settings', 'Light', 'conn-web'), @('nas-connection-settings', 'Dark', 'conn-service'),
    @('nas-connection-settings', 'Light', 'conn-current'), @('nas-connection-settings', 'Light', 'conn-current-reversed'),
    @('nas-connection-settings', 'Light', 'conn-unknown-current'), @('nas-connection-settings', 'Dark', 'conn-unknown'),
    @('nas-connection-settings', 'Light', 'conn-rejected'), @('nas-connection-settings', 'Light', 'conn-conflict'),
    @('nas-connection-settings', 'Light', 'conn-pending'), @('nas-connection-settings', 'Light', 'conn-recovered'),
    @('nas-connection-settings', 'Light', 'conn-search'), @('nas-connection-settings', 'Light', 'conn-switch-target'),
    @('nas-connection-settings', 'Light', 'conn-late-search'), @('nas-connection-settings', 'Light', 'conn-close-busy')
)
$savedEnvironment = @{}
$runResults = [Collections.Generic.List[object]]::new()
$reportPath = Join-Path $review 'results.json'
foreach ($key in @('LANSTASH_SMOKE_SCENARIO', 'LANSTASH_SMOKE_THEME', 'LANSTASH_SMOKE_STATE', 'LANSTASH_SMOKE_WIDTH', 'LANSTASH_SMOKE_HEIGHT', 'LANSTASH_SMOKE_PANE', 'LANSTASH_SMOKE_LANGUAGE', 'LANSTASH_SMOKE_NATIVE_DIAGNOSTICS')) {
    $savedEnvironment[$key] = [Environment]::GetEnvironmentVariable($key, 'Process')
}
try {
    $env:LANSTASH_SMOKE_WIDTH = "$WindowWidth"
    $env:LANSTASH_SMOKE_HEIGHT = "$WindowHeight"
    $env:LANSTASH_SMOKE_PANE = $PaneState
    $env:LANSTASH_SMOKE_LANGUAGE = $Language
    $env:LANSTASH_SMOKE_NATIVE_DIAGNOSTICS = if ($CaptureNativeFailures) { '1' } else { '0' }
    foreach ($case in $cases) {
        if ($Scenarios.Count -gt 0 -and $case[0] -notin $Scenarios) { continue }
        if ($States.Count -gt 0 -and $case[2] -notin $States) { continue }
        $env:LANSTASH_SMOKE_SCENARIO = $case[0]
        $env:LANSTASH_SMOKE_THEME = $case[1]
        $env:LANSTASH_SMOKE_STATE = $case[2]
        $expectsExit = ($case[0] -eq 'office' -and $case[2] -eq 'quit-keep-copies') -or
            ($case[0] -eq 'desktop-lifecycle' -and $case[2] -eq 'quit-keep-voice')
        $started = Get-Date
        $process = Start-Process -FilePath (Join-Path $output 'LanStash.App.exe') -WindowStyle Hidden -PassThru
        $nativeMonitor = $null
        try {
            if ($CaptureNativeFailures) {
                $nativeLog = Join-Path $review ("{0}-{1}-{2}-native.txt" -f $case[0], $case[2], $case[1].ToLowerInvariant())
                $nativeMonitor = [NativeUiCrashMonitor]::Attach($process, (Join-Path $output 'LanStash.App.exe'), $nativeLog)
            }
            $timer = [Diagnostics.Stopwatch]::StartNew()
            do {
                $hasExited = $process.WaitForExit(250)
                $snapshot = Get-Item -LiteralPath (Join-Path $output 'workspace-smoke.png') -ErrorAction SilentlyContinue
                $complete = Get-Item -LiteralPath (Join-Path $output 'smoke-complete.txt') -ErrorAction SilentlyContinue
                if ($hasExited) {
                    # 退出场景必须先完成关闭后副本断言；其他场景仍将任何提前退出视为失败。
                    if ($expectsExit -and $process.ExitCode -eq 0 -and
                        $null -ne $complete -and $complete.LastWriteTime -ge $started) { break }
                    throw "合成宿主提前退出：$case；退出码 $($process.ExitCode)"
                }
            } while (($null -eq $complete -or $complete.LastWriteTime -lt $started) -and $timer.Elapsed.TotalSeconds -lt 30)
            if ($null -eq $snapshot) { throw "没有生成截图：$case" }
            if ($null -eq $complete -or $complete.LastWriteTime -lt $started -or $snapshot.Length -lt 100) { throw "截图尚未完整写入：$case" }
            if ($snapshot.LastWriteTime -lt $started) { throw "没有通过状态断言的新截图：$case" }
            if ($expectsExit -and
                (-not $process.WaitForExit(5000) -or $process.ExitCode -ne 0)) { throw "保留副本退出未正常完成：$case" }
            $label = if ($case[2]) { $case[2] } else { $case[0] }
            if ($Scenarios.Count -ne 1) { $label = $case[0] + '-' + $label }
            $name = "$label-$($case[1].ToLowerInvariant()).png"
        Copy-Item -LiteralPath $snapshot.FullName -Destination (Join-Path $review $name)
        if ($case[0] -eq 'vm-console') {
            $consolePreview = Get-Item -LiteralPath (Join-Path $output 'workspace-console-page.png') -ErrorAction SilentlyContinue
            if ($null -ne $consolePreview -and $consolePreview.LastWriteTime -ge $started) {
                Copy-Item -LiteralPath $consolePreview.FullName -Destination (Join-Path $review ($label + '-page-' + $case[1].ToLowerInvariant() + '.png'))
            }
        }
            Write-Output ("PASS {0} ({1:N1}s)" -f $name, $timer.Elapsed.TotalSeconds)
            $runResults.Add(@{ scenario=$case[0]; theme=$case[1]; state=$case[2]; status='passed'; seconds=$timer.Elapsed.TotalSeconds; artifact=$name })
        }
        catch {
            $failure = $_.Exception.Message
            # 每个失败场景保留自身的新异常，防止后续宿主覆盖唯一诊断文件。
            $diagnostic = Get-Item -LiteralPath (Join-Path $output 'smoke-failure.txt') -ErrorAction SilentlyContinue
            if ($null -ne $diagnostic -and $diagnostic.LastWriteTime -ge $started) {
                Copy-Item -LiteralPath $diagnostic.FullName -Destination (Join-Path $review ("{0}-{1}-{2}-failure.txt" -f $case[0], $case[2], $case[1].ToLowerInvariant()))
            }
            $phase = Get-Item -LiteralPath (Join-Path $output 'smoke-native-phase.txt') -ErrorAction SilentlyContinue
            if ($CaptureNativeFailures -and $null -ne $phase -and $phase.LastWriteTime -ge $started) {
                Copy-Item -LiteralPath $phase.FullName -Destination (Join-Path $review ("{0}-{1}-{2}-phase.txt" -f $case[0], $case[2], $case[1].ToLowerInvariant()))
            }
            $runResults.Add(@{ scenario=$case[0]; theme=$case[1]; state=$case[2]; status='failed'; seconds=$timer.Elapsed.TotalSeconds; error=$failure })
            if (-not $ContinueOnFailure) { throw }
            Write-Warning ("FAIL {0}/{1}/{2}: {3}" -f $case[0], $case[1], $case[2], $failure)
        }
        finally {
            if (-not $process.HasExited) { $process.Kill(); $process.WaitForExit() }
            if ($null -ne $nativeMonitor) { $nativeMonitor.Dispose() }
            $process.Dispose()
            # 正式回归产物，不含设备数据；即使中途停止，也保留已完成场景的真实状态。
            @{ schemaVersion=1; language=$Language; width=$WindowWidth; height=$WindowHeight; results=$runResults.ToArray() } |
                ConvertTo-Json -Depth 5 | Set-Content -LiteralPath $reportPath -Encoding utf8
        }
    }
}
finally {
    foreach ($key in $savedEnvironment.Keys) {
        [Environment]::SetEnvironmentVariable($key, $savedEnvironment[$key], 'Process')
    }
}
if ($runResults.Count -eq 0) { throw '没有匹配的原生回归场景。' }
$failedCount = @($runResults | Where-Object { $_.status -eq 'failed' }).Count
Write-Output "原生界面合成回归完成：$review；总数 $($runResults.Count)，失败 $failedCount"
if ($failedCount -gt 0) { throw "原生回归存在 $failedCount 项失败，详见 results.json。" }
